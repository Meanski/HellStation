#!/usr/bin/env python3
"""Generate Redivivus/port/link_data.cpp from Redivivus/d2_link_support.s.

The .s holds data symbols with real bytes from Game.exe and do-nothing function
stubs, in i386 PE syntax. Port targets need the same definitions without x86
assembly or PE symbol decoration, so this turns each entry into C++ that defines
the identical (ELF-spelled) symbol through an asm label.

    tools/port/gen_link_data.py [in.s] [out.cpp]
"""
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "Redivivus/d2_link_support.s"
dst = sys.argv[2] if len(sys.argv) > 2 else "Redivivus/port/link_data.cpp"

lines = open(src).read().splitlines()
section, entries, cur = "text", [], None
for raw in lines:
    line = raw.split("#", 1)[0].strip()
    if not line:
        continue
    if line.startswith(".section"):
        section = "rodata" if ".rdata" in line else "data"
    elif line == ".text":
        section = "text"
    elif line.startswith(".globl"):
        cur = {"pe": line.split()[1], "section": section, "longs": [], "pop": 0}
        entries.append(cur)
    elif cur and line.startswith(".long"):
        cur["longs"] += [int(v, 0) for v in line.split(None, 1)[1].split(",")]
    elif cur and re.match(r"ret\s+\$(\d+)", line):
        cur["pop"] = int(re.match(r"ret\s+\$(\d+)", line).group(1))


def elf_name(pe):
    # i386 PE prefixes every C and C++ symbol with '_'; stdcall adds '@<bytes>'.
    name = pe[1:] if pe.startswith("_") else pe
    return re.sub(r"@\d+$", "", name)


out = [
    "// GENERATED by tools/port/gen_link_data.py from Redivivus/d2_link_support.s.",
    "// Do not edit; rerun the script when the .s changes.",
    "//",
    "// Port-target equivalent of the x86 PE assembly: the same symbols, the same data",
    "// bytes, the same do-nothing stubs. Symbol names are given as asm labels so the",
    "// C++ mangled names in the .s are preserved exactly.",
    "#include <cstdint>",
    "",
    "#if defined(__i386__)",
    "#  define HS_STDCALL __attribute__((__stdcall__))",
    "#else",
    "#  define HS_STDCALL",
    "#endif",
    "",
]
for i, e in enumerate(entries):
    name = elf_name(e["pe"])
    if e["section"] != "text":
        const = "const " if e["section"] == "rodata" else ""
        vals = ", ".join(str(v) for v in e["longs"]) or "0"
        n = max(1, len(e["longs"]))
        out.append(f'extern "C" {const}uint32_t hs_link_data_{i}[{n}] __asm__("{name}");')
        out.append(f'extern "C" __attribute__((used)) {const}uint32_t hs_link_data_{i}[{n}] = {{ {vals} }};')
    elif e["pop"]:
        params = ", ".join(["uint32_t"] * (e["pop"] // 4))
        out.append(f'extern "C" HS_STDCALL uint32_t hs_link_stub_{i}({params}) __asm__("{name}");')
        out.append(f'extern "C" __attribute__((used)) HS_STDCALL uint32_t hs_link_stub_{i}({params}) {{ return 0; }}')
    else:
        out.append(f'extern "C" uint32_t hs_link_stub_{i}() __asm__("{name}");')
        out.append(f'extern "C" __attribute__((used)) uint32_t hs_link_stub_{i}() {{ return 0; }}')
    out.append("")

open(dst, "w").write("\n".join(out))
print(f"{dst}: {len(entries)} symbols")
